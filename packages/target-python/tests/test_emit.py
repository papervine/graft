def ir_with(
    *,
    types: list[dict[str, Any]] | None = None,
    resources: list[dict[str, Any]] | None = None,
    pagination: list[dict[str, Any]] | None = None,
    errors: dict[str, Any] | None = None,
    servers: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "irVersion": "1.2.0",
        "service": {
            "name": {"tokens": ["acme"]},
            "displayName": "Acme",
            "version": "1.0",
            "docs": DOCS,
            "servers": servers
            or [
                {
                    "url": "https://api.acme.com",
                    "default": True,
                    "docs": DOCS,
                    "variables": [],
                }
            ],
            "auth": [{"kind": "bearer", "docs": DOCS}],
            "constantHeaders": {},
        },
        "types": types or [],
        "resources": resources or [],
        "errors": errors or {"byStatus": []},
        "pagination": pagination or [],
    }


def field(
    name: str, type_ref: dict[str, Any], *, required: bool = True, wire: str | None = None
) -> dict[str, Any]:
    return {
        "name": {"tokens": name.split("_")},
        "wireName": wire or name,
        "type": type_ref,
        "required": required,
        "serverOwned": False,
        "readOnly": False,
        "writeOnly": False,
        "deprecated": False,
        "docs": DOCS,
    }


STR = {"kind": "primitive", "type": "string"}


def emit(ir: dict[str, Any]) -> dict[str, str]:
    files = PythonEmitter(ir, {"packageName": "acme"}, BRAND).emit({})
    return {f["path"]: f["contents"] for f in files}


