class TestProtocol:
    def test_handshake_declares_gates_and_a_line_comment(self) -> None:
        result = subprocess.run(
            [sys.executable, "-m", "graft_target_python", HANDSHAKE_FLAG],
            capture_output=True,
            text=True,
            cwd=str(Path(__file__).resolve().parents[1] / "src"),
            check=True,
        )
        handshake = json.loads(result.stdout)
        assert handshake["name"] == "python"
        # `#` is what lets the core find preservation markers without knowing Python.
        assert handshake["lineComment"] == "#"
        gate_names = [g["name"] for g in handshake["gates"]]
        assert "mypy --strict" in gate_names
        # A formatter's exit code is not a verdict; the typechecker's is.
        kinds = {g["name"]: g.get("kind") for g in handshake["gates"]}
        assert kinds["ruff format"] == "fix"
        assert kinds["mypy --strict"] == "verify"
        # The typechecker must not be skippable.
        optional = {g["name"]: g.get("optional", False) for g in handshake["gates"]}
        assert optional["mypy --strict"] is False

    def test_empty_stdin_is_an_error_not_a_traceback(self) -> None:
        result = subprocess.run(
            [sys.executable, "-m", "graft_target_python"],
            input="",
            capture_output=True,
            text=True,
            cwd=str(Path(__file__).resolve().parents[1] / "src"),
        )
        assert result.returncode == 2
        assert "expected IR JSON" in result.stderr
        assert "Traceback" not in result.stderr


class TestIdempotencyHeader:
    """Guards the threading, not the behaviour.

    The runtime already honoured a custom header; the target simply never passed one on, so
    `idempotencyHeader` in graft.yaml was accepted, validated, and silently discarded. That failure
    mode leaves every gate green — the SDK imports, typechecks, and formats — which is why it needs a
    test naming the config key rather than a review.
    """

    def test_a_configured_header_reaches_the_client(self) -> None:
        files = PythonEmitter(
            ir_with(), {"packageName": "acme", "idempotencyHeader": "X-Idempotency-Key"}, BRAND
        ).emit({})
        client = next(f["contents"] for f in files if f["path"].endswith("_client.py"))
        # Quote-agnostic: the emitter uses repr(), ruff format normalises to double quotes later.
        assert "idempotency_header=" in client
        assert "X-Idempotency-Key" in client

    def test_no_configuration_leaves_the_runtime_default(self) -> None:
        files = PythonEmitter(ir_with(), {"packageName": "acme"}, BRAND).emit({})
        client = next(f["contents"] for f in files if f["path"].endswith("_client.py"))
        # Absent entirely, rather than passed as an empty string that would override the default.
        assert "idempotency_header" not in client


class TestServerVariables:
    """A templated server URL (SPEC.md §3.4.0.2).

    graft passed the template through untouched once, so every request went to a host containing
    literal braces. The core now resolves the default; the target's job is to make each variable
    configurable without asking a caller to assemble a hostname.
    """

    TEMPLATED = [
        {
            "url": "https://us-east-1.api.example.com/v2",
            "urlTemplate": "https://{region}.api.example.com/{version}",
            "variables": [
                {
                    "wireName": "region",
                    "name": {"tokens": ["region"]},
                    "default": "us-east-1",
                    "enum": ["us-east-1", "eu-west-1"],
                    "description": "Data residency.",
                },
                {"wireName": "version", "name": {"tokens": ["version"]}, "default": "v2"},
            ],
            "default": True,
            "docs": DOCS,
        }
    ]

    def _client(self, servers: list[dict[str, Any]] | None = None) -> str:
        files = PythonEmitter(ir_with(servers=servers), {"packageName": "acme"}, BRAND).emit({})
        return next(f["contents"] for f in files if f["path"].endswith("_client.py"))

    def test_variables_become_keyword_arguments_and_an_f_string(self) -> None:
        client = self._client(self.TEMPLATED)
        # An enum becomes a Literal: the spec listed the valid values, and widening them to `str`
        # would leave a caller guessing at a region name.
        assert "region: Literal['us-east-1', 'eu-west-1'] | None = None" in client
        assert "version: str | None = None" in client
        assert (
            "base_url=base_url or f\"https://{region or 'us-east-1'}"
            ".api.example.com/{version or 'v2'}\"" in client
        )

    def test_both_the_sync_and_async_client_get_them(self) -> None:
        # Two constructors are emitted from one code path, so a change that reaches only one of them
        # is a silent asymmetry a caller discovers at runtime.
        assert self._client(self.TEMPLATED).count("region: Literal[") == 2

    def test_an_untemplated_server_stays_a_plain_literal(self) -> None:
        client = self._client()
        assert "base_url=base_url or 'https://api.acme.com'" in client
        # No variable, so no parameter for one. Matched on the parameter form rather than the bare
        # word: `# region client` is a preserve marker and appears in every generated client.
        assert "region:" not in client
