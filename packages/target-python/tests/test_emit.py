class TestNaming:
    def test_tokens_become_snake_case(self) -> None:
        assert snake(["user", "id"]) == "user_id"

    @pytest.mark.parametrize(
        ("wire", "expected"),
        [
            # `id` and `type` are the two commonest field names in real APIs and are never emitted
            # as annotations, so suffixing them would mark almost every model as machine-made.
            ("id", "id"),
            ("type", "type"),
            # Keywords are unavoidable — `self.from` is a syntax error.
            ("from", "from_"),
            ("class", "class_"),
            # These *are* emitted as annotations, so a field with the name shadows it class-wide.
            ("object", "object_"),
            ("str", "str_"),
            # A pydantic BaseModel method. GitHub has a field called `validate`.
            ("validate", "validate_"),
        ],
    )
    def test_attribute_names(self, wire: str, expected: str) -> None:
        assert safe_attribute(wire) == expected

    def test_method_names_keep_builtins(self) -> None:
        # `client.widgets.list()` is correct; `list_()` is the tell-tale generated-code smell.
        assert safe_method_name("list") == "list"
        assert safe_method_name("delete") == "delete"
        assert safe_method_name("import") == "import_"

    def test_locals_avoid_builtins(self) -> None:
        # Stricter than attributes: a bare `list` inside a function body really does shadow it.
        assert safe_identifier("list") == "list_"
        assert safe_identifier("id") == "id_"

    def test_colliding_attributes_are_disambiguated(self) -> None:
        # Two GitHub properties both sanitise to `_1`; the second silently replaced the first.
        taken: set[str] = set()
        assert unique_attribute("1", taken) == "_1"
        assert unique_attribute("1", taken) == "_1_2"

    @pytest.mark.parametrize(
        ("resource_id", "expected"),
        [
            # Twilio's resource ids are PascalCase, which produced `Api20100401Address.py`.
            ("Api20100401Address", "api20100401_address"),
            ("orgs.invoices", "orgs_invoices"),
            ("HTTPServer", "http_server"),
            ("already_snake", "already_snake"),
        ],
    )
    def test_module_names_are_pep8(self, resource_id: str, expected: str) -> None:
        assert module_name(resource_id) == expected

    def test_snake_from_mixed_handles_capital_runs(self) -> None:
        assert snake_from_mixed("parseHTTPResponse") == "parse_http_response"


