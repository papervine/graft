class TestBuilder:
    def test_docstring_escapes_a_trailing_quote(self) -> None:
        # Stripe: `The user ID, if type is set to "user"`. A trailing quote made the closing
        # delimiter four quotes, an unterminated string.
        module = Module()
        module.add(Class(name="X", docstring='ends with a quote "user"'))
        rendered = module.render()
        compile(rendered, "<test>", "exec")  # the real assertion: it parses

    def test_docstring_escapes_embedded_triple_quotes(self) -> None:
        module = Module()
        module.add(Class(name="X", docstring='has """ inside'))
        compile(module.render(), "<test>", "exec")

    def test_long_docstrings_are_wrapped(self) -> None:
        # `ruff format` does not reflow prose, so an unwrapped description fails the line limit.
        module = Module()
        module.add(Class(name="X", docstring="word " * 80))
        for line in module.render().split("\n"):
            assert len(line) <= 100, line

    def test_indented_blocks_are_not_reflowed(self) -> None:
        # Rewrapping a code sample is how a generator turns a working example into a broken one.
        code = "    client.widgets.list(limit=50, offset=0, order='desc', extra='keep this exact')"
        module = Module()
        module.add(Class(name="X", docstring=f"Example:\n\n{code}"))
        assert code in module.render()

    def test_markdown_list_items_are_wrapped_and_keep_their_marker(self) -> None:
        # GitHub's descriptions are full of two-space bullets; treating them as code left 222
        # unwrapped lines. The bullet sits after a summary because the *first* line of a docstring
        # is deliberately un-indented — PEP 257 puts it against the opening quotes.
        module = Module()
        module.add(Class(name="X", docstring="Summary.\n\n" + " - " + ("word " * 40)))
        rendered = module.render()
        assert " - word" in rendered
        # A wrapped continuation is indented under the text, so markdown still reads it as one item.
        assert "   word" in rendered
        for line in rendered.split("\n"):
            assert len(line) <= 100, line

    def test_imports_are_grouped_and_deduplicated(self) -> None:
        module = Module()
        module.use_future_annotations()
        module.import_from("typing", "Literal")
        module.import_from("typing", "Literal", "TypeAlias")
        module.import_from("pydantic", "BaseModel")
        module.import_from("._core", "BaseClient")
        rendered = module.render()
        assert rendered.count("from typing import") == 1
        assert "from typing import Literal, TypeAlias" in rendered
        assert rendered.index("from __future__") < rendered.index("from typing")
        assert rendered.index("from typing") < rendered.index("from pydantic")
        assert rendered.index("from pydantic") < rendered.index("from ._core")

    def test_urllib_is_stdlib_not_third_party(self) -> None:
        module = Module()
        module.import_from("urllib.parse", "quote")
        module.import_from("pydantic", "BaseModel")
        rendered = module.render()
        assert rendered.index("urllib.parse") < rendered.index("pydantic")

    def test_keyword_only_marker_is_emitted_once(self) -> None:
        fn = Function(
            name="f",
            params=[
                Param("self"),
                Param("a", annotation="str"),
                Param("b", annotation="str", default="None", keyword_only=True),
                Param("c", annotation="str", default="None", keyword_only=True),
            ],
            returns="None",
            body=["pass"],
        )
        signature = fn.render()[0]
        assert signature.count("*") == 1
        assert signature == "def f(self, a: str, *, b: str = None, c: str = None) -> None:"

    def test_open_enums_union_with_str(self) -> None:
        # A server adds a value without warning; an exhaustive type would make that a decode failure.
        assert literal_union(["a", "b"], open_ended=True) == "Literal['a', 'b'] | str"
        assert literal_union(["a"], open_ended=False) == "Literal['a']"

    def test_class_trailing_text_stays_inside_the_body(self) -> None:
        # The preservation markers must sit inside the class, or a user's method between them is a
        # top-level syntax error.
        cls = Class(name="X", methods=[Function(name="m", body=["pass"])], trailing=["# region x"])
        rendered = "\n".join(cls.render())
        assert "    # region x" in rendered
        compile(rendered, "<test>", "exec")


