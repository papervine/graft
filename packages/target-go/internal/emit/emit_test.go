func TestDocCommentUsesNameColonForm(t *testing.T) {
	// A generator cannot conjugate a summary into English — "ListMembers list members" is not a
	// sentence. `Name: Summary` is the form Google's generated Go clients use.
	got := DocComment("", "ListMembers", Docs{Summary: "List members of an organization"})
	if !strings.HasPrefix(got, "// ListMembers: List members") {
		t.Errorf("DocComment = %q", got)
	}
}

func TestDocCommentLeavesAuthoredSentencesAlone(t *testing.T) {
	got := DocComment("", "Widget", Docs{Summary: "Widget is a thing you can buy."})
	if !strings.HasPrefix(got, "// Widget is a thing") {
		t.Errorf("DocComment rewrote an already-correct sentence: %q", got)
	}
}

func TestDocCommentWrapsProse(t *testing.T) {
	// gofmt does not reflow comments, so wrapping has to happen here.
	long := strings.Repeat("word ", 80)
	for _, line := range strings.Split(DocComment("\t", "X", Docs{Summary: long}), "\n") {
		if len(line) > 100 {
			t.Fatalf("line of %d chars: %q", len(line), line)
		}
	}
}

func TestDocCommentPreservesIndentedCode(t *testing.T) {
	// Rewrapping a code sample is how a generator turns a working example into a broken one.
	code := "\tit := client.Widgets.List(ctx, nil)"
	// Asserted through a rendered file, because gofmt is what normalises `// \t` to `//\t` — and the
	// point of the test is that the *content* survives unreflowed, not what the raw prefix looks like
	// before formatting.
	file := NewFile("demo")
	file.Add(DocComment("", "X", Docs{}, "Example:\n\n"+code) + "type X struct{}")
	rendered, err := file.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(rendered, "//\tit := client.Widgets.List(ctx, nil)") {
		t.Errorf("code block was reflowed:\n%s", rendered)
	}
}

func TestDocCommentStripsControlCharacters(t *testing.T) {
	got := DocComment("", "X", Docs{Summary: "before\x00\x07after"})
	if strings.ContainsAny(got, "\x00\x07") {
		t.Errorf("control characters survived: %q", got)
	}
}

func TestFileRenderIsGofmtted(t *testing.T) {
	file := NewFile("demo")
	file.Import("context")
	// Deliberately misformatted input: go/format is what decides layout, not this string.
	file.Add("type   Widget    struct {\nID   string\n}")
	got, err := file.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(got, "type Widget struct {") {
		t.Errorf("not gofmt-formatted:\n%s", got)
	}
}

func TestFileRenderReportsInvalidGoWithTheText(t *testing.T) {
	// When generation produces invalid Go, the *text* is what a maintainer needs; returning only an
	// error would hide the evidence.
	file := NewFile("demo")
	file.Add("func broken( {")
	text, err := file.Render()
	if err == nil {
		t.Fatal("expected an error")
	}
	if !strings.Contains(text, "func broken") {
		t.Error("the unformatted text was not returned alongside the error")
	}
}

func TestImportsAreGroupedStdlibFirst(t *testing.T) {
	file := NewFile("demo")
	file.Import("github.com/acme/x/internal/core")
	file.Import("context")
	got, err := file.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if strings.Index(got, `"context"`) > strings.Index(got, "internal/core") {
		t.Errorf("imports not grouped stdlib-first:\n%s", got)
	}
}

