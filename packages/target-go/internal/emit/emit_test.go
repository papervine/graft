func TestSanityCatchesAMisnamedField(t *testing.T) {
	// The check that exists because no gate over the *output* can catch a target reading the wrong
	// IR field: the output is well-formed, it just does nothing.
	ir := testIR(t, minimalIR)
	loose := map[string]any{
		"resources": []any{map[string]any{
			"methods": []any{map[string]any{"body": map[string]any{}, "http": map[string]any{"params": []any{}}}},
		}},
	}
	problems := Sanity(ir, loose)
	if len(problems) == 0 {
		t.Error("Sanity did not notice that resources failed to decode")
	}
}

