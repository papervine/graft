// hasField reports whether source declares a struct field of the given name and type, ignoring the
// column alignment gofmt applies.
func hasField(source, name, goType string) bool {
	for _, line := range strings.Split(source, "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == name && fields[1] == goType {
			return true
		}
	}
	return false
}

func testIR(t *testing.T, body string) *IR {
	t.Helper()
	var ir IR
	if err := json.Unmarshal([]byte(body), &ir); err != nil {
		t.Fatalf("decoding test IR: %v", err)
	}
	return &ir
}

const minimalIR = `{
  "irVersion": "1.2.0",
  "service": {
    "name": {"tokens":["acme"]}, "displayName": "Acme", "version": "1.0", "docs": {},
    "servers": [{"url":"https://api.acme.com","default":true,"docs":{}}],
    "auth": [{"kind":"bearer","docs":{}}], "constantHeaders": {}
  },
  "types": [], "resources": [], "errors": {"byStatus": []}, "pagination": []
}`

func emitFiles(t *testing.T, ir *IR, opts string) map[string]string {
	t.Helper()
	e := New(ir, json.RawMessage(opts), testBrand)
	files, err := e.Emit(map[string]string{})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = f.Contents
	}
	return out
}

func TestSelfReferentialStructBecomesAPointer(t *testing.T) {
	// Go embeds a struct by value, so `type A struct { A A }` is infinitely sized and does not
	// compile. Stripe has one. The IR's `cyclic` flag says the type participates in a cycle but not
	// which *field* closes it, so the edge is computed in the target.
	ir := testIR(t, `{
      "irVersion":"1.2.0",
      "service":{"name":{"tokens":["acme"]},"version":"1","docs":{},"servers":[],"auth":[],"constantHeaders":{}},
      "types":[{"kind":"object","id":"Node","name":{"tokens":["node"]},"docs":{},"role":"read","cyclic":true,
        "fields":[
          {"name":{"tokens":["id"]},"wireName":"id","type":{"kind":"primitive","type":"string"},
           "required":true,"serverOwned":false,"readOnly":false,"writeOnly":false,"deprecated":false,"docs":{}},
          {"name":{"tokens":["parent"]},"wireName":"parent","type":{"kind":"named","id":"Node"},
           "required":true,"serverOwned":false,"readOnly":false,"writeOnly":false,"deprecated":false,"docs":{}}
        ]}],
      "resources":[],"errors":{"byStatus":[]},"pagination":[]}`)
	models := emitFiles(t, ir, `{}`)["models.go"]
	// Whitespace-insensitive: gofmt aligns struct fields into columns, so an exact-spacing assertion
	// would test the formatter rather than the generator.
	if !hasField(models, "Parent", "*Node") {
		t.Errorf("a self-referential field must be a pointer:\n%s", models)
	}
	// And a scalar in the same struct must stay a value.
	if !hasField(models, "ID", "string") {
		t.Errorf("a required scalar was pointer-ised unnecessarily:\n%s", models)
	}
}

func TestEnumConstantsDoNotCollideWithTypes(t *testing.T) {
	// Go puts types and constants in one namespace. GitHub declares a struct `EventComment` and an
	// `Event` enum with a `COMMENT` member, and the second redeclared the first.
	ir := testIR(t, `{
      "irVersion":"1.2.0",
      "service":{"name":{"tokens":["acme"]},"version":"1","docs":{},"servers":[],"auth":[],"constantHeaders":{}},
      "types":[
        {"kind":"object","id":"EventComment","name":{"tokens":["event","comment"]},"docs":{},"role":"read","cyclic":false,"fields":[]},
        {"kind":"enum","id":"Event","name":{"tokens":["event"]},"docs":{},"open":true,
         "members":[{"name":{"tokens":["comment"]},"wireValue":"\"COMMENT\"","docs":{}}]}
      ],
      "resources":[],"errors":{"byStatus":[]},"pagination":[]}`)
	models := emitFiles(t, ir, `{}`)["models.go"]
	if strings.Count(models, "EventComment ") > 1 && strings.Contains(models, "EventComment Event") {
		// The constant must have been renamed, not redeclared.
		t.Errorf("enum constant collided with a type:\n%s", models)
	}
	if !strings.Contains(models, "type EventComment struct") {
		t.Errorf("the struct lost its name:\n%s", models)
	}
}

func TestNoModulePathWarns(t *testing.T) {
	// A wrong module path breaks `go get` for every consumer, so it cannot be silent.
	ir := testIR(t, minimalIR)
	e := New(ir, json.RawMessage(`{}`), testBrand)
	if len(e.Warnings()) == 0 {
		t.Error("expected a warning when modulePath is unset")
	}
	if !strings.Contains(e.Warnings()[0].Message, "modulePath") {
		t.Errorf("warning = %q", e.Warnings()[0].Message)
	}
}

