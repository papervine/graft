// TestTemplatedServerBecomesTypedOptions checks the Go answer to a union: a named string type with
// constants, which is what a caller can discover in an editor.
//
// The base URL is left as a template for the runtime to resolve, because Go applies functional options
// *after* the options struct is built — a constructor substituting inline would assemble the URL before
// WithRegion ever ran.
func TestTemplatedServerBecomesTypedOptions(t *testing.T) {
	client := emitFiles(t, testIR(t, templatedServerIR), `{"packageName":"acme"}`)["client.go"]

	for _, want := range []string{
		"type Region string",
		`RegionUsEast1 Region = "us-east-1"`,
		`RegionEuWest1 Region = "eu-west-1"`,
		"func WithRegion(v Region) Option {",
		// No enum, so no named type and no constants — a bare string is all the spec supports.
		"func WithVersion(v string) Option {",
		`BaseURLTemplate: "https://{region}.api.example.com/{version}"`,
		`"region":  "us-east-1"`,
		`"version": "v2"`,
		// The description carries into the doc comment, since that is where a caller reads it.
		"// Data residency.",
	} {
		if !containsNormalized(client, want) {
			t.Errorf("client.go is missing %q", want)
		}
	}

	// A resolved BaseURL alongside the template would win in the runtime and pin the defaults,
	// making every With* option silently useless.
	if strings.Contains(client, "BaseURL:") {
		t.Errorf("a templated server must not also set BaseURL:\n%s", client)
	}
}

// TestUntemplatedServerKeepsAPlainBaseURL is the other half: nothing changes for the common case.
func TestUntemplatedServerKeepsAPlainBaseURL(t *testing.T) {
	client := emitFiles(t, testIR(t, minimalIR), `{"packageName":"acme"}`)["client.go"]
	if !containsNormalized(client, `BaseURL: "https://api.acme.com"`) {
		t.Errorf("expected a plain BaseURL:\n%s", client)
	}
	if strings.Contains(client, "BaseURLTemplate") {
		t.Errorf("an untemplated server must not set BaseURLTemplate:\n%s", client)
	}
}

// TestSchemasFileIsEmittedForPrimitiveOnlyResponses pins a spec shape the corpus does not have.
//
// The emit gate read the *named type* table, but `responseSchemas` lives in the same file and is
// referenced by any method whose response has a descriptor. A spec returning `[]string` has no named
// types and a non-empty response map, so the file was skipped and the SDK referenced two undefined
// symbols. Every corpus spec declares named types, which is why it compiled everywhere.
func TestSchemasFileIsEmittedForPrimitiveOnlyResponses(t *testing.T) {
	files := emitFiles(t, testIR(t, primitiveResponseIR), `{"packageName":"acme"}`)
	schemas, ok := files["schemas.go"]
	if !ok {
		t.Fatalf("schemas.go was not emitted; files: %v", keysOf(files))
	}
	if !strings.Contains(schemas, "responseSchemas = core.MustParseSchemaTable") {
		t.Errorf("schemas.go does not define responseSchemas:\n%s", schemas)
	}
}

// containsNormalized reports whether source contains want, ignoring how gofmt aligned it.
//
// gofmt pads struct field values into columns, so `BaseURL: "x"` is emitted as `BaseURL:   "x"`. An
// exact match makes a test depend on how many other fields happen to be in the literal.
func containsNormalized(source, want string) bool {
	collapse := func(text string) string {
		for strings.Contains(text, "  ") {
			text = strings.ReplaceAll(text, "  ", " ")
		}
		return text
	}
	return strings.Contains(collapse(source), collapse(want))
}

func keysOf(files map[string]string) []string {
	out := make([]string, 0, len(files))
	for name := range files {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

