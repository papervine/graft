package besdk.target.java;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

final class EmitterTest {

  /**
   * What the core sends in {@code TargetInput.brand}.
   *
   * <p>Required rather than defaulted: a hardcoded fallback in the target is exactly what carrying
   * it over the protocol exists to prevent (SPEC.md §1.2).
   */
  private static final Map<String, Object> BRAND =
      Map.of(
          "name", "besdk",
          "title", "besdk",
          "homepage", "https://example.invalid",
          "configFile", "besdk.yaml",
          "generatedNotice", "Code generated by besdk. DO NOT EDIT.",
          "attribution", "_Generated by besdk._");

  private static Map<String, Object> ir(Map<String, Object> overrides) {
    Map<String, Object> out = new LinkedHashMap<>();
    out.put("irVersion", "1.5.0");
    out.put(
        "service",
        Map.of(
            "name", Map.of("tokens", List.of("acme")),
            "displayName", "Acme",
            "version", "1.0",
            "docs", Map.of(),
            "servers",
                List.of(
                    Map.of(
                        "url", "https://api.acme.com", "default", Boolean.TRUE, "docs", Map.of())),
            "auth", List.of(Map.of("kind", "bearer", "docs", Map.of())),
            "constantHeaders", Map.of()));
    out.put("types", List.of());
    out.put("resources", List.of());
    out.put("errors", Map.of("byStatus", List.of()));
    out.put("pagination", List.of());
    out.putAll(overrides);
    return out;
  }

  private static Map<String, String> emit(Map<String, Object> ir, Map<String, Object> options) {
    Map<String, Object> allOptions = new LinkedHashMap<>(Map.of("packageName", "com.acme:sdk"));
    allOptions.putAll(options);
    Emitter emitter = new Emitter(ir, allOptions, BRAND);
    Map<String, String> out = new LinkedHashMap<>();
    for (Emitter.File file : emitter.emit(Map.of())) {
      out.put(file.path(), file.contents());
    }
    return out;
  }

  private static Map<String, Object> widgetType(Map<String, Object> fieldOverrides) {
    Map<String, Object> field = new LinkedHashMap<>();
    field.put("name", Map.of("tokens", List.of("id")));
    field.put("wireName", "id");
    field.put("type", Map.of("kind", "primitive", "type", "string"));
    field.put("required", Boolean.TRUE);
    field.put("serverOwned", Boolean.TRUE);
    field.put("readOnly", Boolean.FALSE);
    field.put("writeOnly", Boolean.FALSE);
    field.put("deprecated", Boolean.FALSE);
    field.put("docs", Map.of());
    field.putAll(fieldOverrides);
    return Map.of(
        "id",
        "Widget",
        "kind",
        "object",
        "name",
        Map.of("tokens", List.of("widget")),
        "role",
        "read",
        "cyclic",
        Boolean.FALSE,
        "docs",
        Map.of(),
        "fields",
        List.of(field));
  }

  @Test
  void readModelsAreRecords() {
    // A decoded response is a value: immutable, equal by content, useful toString for free. That is
    // exactly
    // what a record is, and it is why no other target's read model is this short.
    String widget =
        emit(ir(Map.of("types", List.of(widgetType(Map.of())))), Map.of())
            .get("src/main/java/com/acme/sdk/Widget.java");
    assertNotNull(widget);
    // Asserted without the formatter's line breaking: these tests see the emitter's output, and
    // google-java-format runs later as a gate over the written files.
    assertTrue(widget.contains("public record Widget("), widget);
    assertTrue(widget.contains("String id"), widget);
  }

  @Test
  void aWriteModelGetsABuilder() {
    // Java has neither keyword arguments nor default parameter values, so a body with several
    // optional fields
    // has no usable constructor. PHP and Python need no builder for the same shape.
    Map<String, Object> type = new LinkedHashMap<>(widgetType(Map.of()));
    type.put("role", "create");
    String source =
        emit(ir(Map.of("types", List.of(type))), Map.of())
            .get("src/main/java/com/acme/sdk/Widget.java");
    assertTrue(source.contains("public static Builder builder()"), source);
    assertTrue(source.contains("public static final class Builder"), source);
  }

  @Test
  void aReadModelGetsNoBuilder() {
    String source =
        emit(ir(Map.of("types", List.of(widgetType(Map.of())))), Map.of())
            .get("src/main/java/com/acme/sdk/Widget.java");
    // A read model is always fully populated, so a constructor is honest there.
    assertFalse(source.contains("public static final class Builder"));
  }

  @Test
  void anOptionalPrimitiveIsBoxedAndARequiredOneIsNot() {
    // A primitive cannot be null and Java has no other way to say "absent", so nullability decides
    // boxing.
    // This is a language constraint, not a style choice.
    Map<String, Object> required =
        new LinkedHashMap<>(Map.of("type", Map.of("kind", "primitive", "type", "integer")));
    String withRequired =
        emit(ir(Map.of("types", List.of(widgetType(required)))), Map.of())
            .get("src/main/java/com/acme/sdk/Widget.java");
    assertTrue(withRequired.contains("long id"), withRequired);

    Map<String, Object> optional = new LinkedHashMap<>(required);
    optional.put("required", Boolean.FALSE);
    String withOptional =
        emit(ir(Map.of("types", List.of(widgetType(optional)))), Map.of())
            .get("src/main/java/com/acme/sdk/Widget.java");
    assertTrue(withOptional.contains("Long id"), withOptional);
  }

  @Test
  void anEnumIsNativeAndDecodedWithFromWire() {
    Map<String, Object> type =
        Map.of(
            "id", "Status",
            "kind", "enum",
            "name", Map.of("tokens", List.of("status")),
            "docs", Map.of(),
            "members",
                List.of(
                    Map.of(
                        "name",
                        Map.of("tokens", List.of("active")),
                        "wireValue",
                        "active",
                        "docs",
                        Map.of()),
                    Map.of(
                        "name",
                        Map.of("tokens", List.of("us", "east", "1")),
                        "wireValue",
                        "us-east-1",
                        "docs",
                        Map.of())));
    String source =
        emit(ir(Map.of("types", List.of(type))), Map.of())
            .get("src/main/java/com/acme/sdk/Status.java");
    assertTrue(source.contains("public enum Status implements Query.WireValued"), source);
    assertTrue(source.contains("ACTIVE(\"active\")"), source);
    // Separators become underscores rather than being dropped, which is what every hand-written
    // Java enum does.
    assertTrue(source.contains("US_EAST_1(\"us-east-1\")"), source);
    // `fromWire` returns null for an unknown member: a server adding a value must not crash the
    // client.
    assertTrue(source.contains("public static Status fromWire(String value)"), source);
  }

  @Test
  void theHttpVerbComesFromTheIrRatherThanADefault() {
    // The bug this pins came from PHP: the emitter read `http.method`, which the IR does not have,
    // and every
    // operation was emitted as a GET — silently, past every gate.
    Map<String, Object> method =
        Map.of(
            "name", Map.of("tokens", List.of("create")),
            "operationId", "createWidget",
            "docs", Map.of(),
            "deprecated", Boolean.FALSE,
            "http", Map.of("verb", "post", "path", "/widgets", "params", List.of()),
            "response", Map.of("kind", "empty", "statusCode", 204));
    Map<String, Object> resource =
        Map.of(
            "id", "widgets",
            "name", Map.of("tokens", List.of("widgets")),
            "docs", Map.of(),
            "subresources", List.of(),
            "methods", List.of(method));
    String source =
        emit(ir(Map.of("resources", List.of(resource))), Map.of())
            .get("src/main/java/com/acme/sdk/Widgets.java");
    assertTrue(source.contains("client.request(\"POST\""), source);
    assertFalse(source.contains("client.request(\"GET\""));
  }

  @Test
  void queryAndPathParametersComeFromOneParamsList() {
    // `http.params` is one list discriminated by `location`, not `pathParams`/`queryParams`.
    Map<String, Object> pathParam =
        Map.of(
            "name",
            Map.of("tokens", List.of("id")),
            "wireName",
            "id",
            "location",
            "path",
            "type",
            Map.of("kind", "primitive", "type", "string"),
            "required",
            Boolean.TRUE,
            "deprecated",
            Boolean.FALSE,
            "docs",
            Map.of());
    Map<String, Object> queryParam =
        Map.of(
            "name",
            Map.of("tokens", List.of("expand")),
            "wireName",
            "expand",
            "location",
            "query",
            "type",
            Map.of("kind", "primitive", "type", "string"),
            "required",
            Boolean.FALSE,
            "deprecated",
            Boolean.FALSE,
            "docs",
            Map.of());
    Map<String, Object> method =
        Map.of(
            "name", Map.of("tokens", List.of("get")),
            "operationId", "getWidget",
            "docs", Map.of(),
            "deprecated", Boolean.FALSE,
            "http",
                Map.of(
                    "verb",
                    "get",
                    "path",
                    "/widgets/{id}",
                    "params",
                    List.of(pathParam, queryParam)),
            "response", Map.of("kind", "empty", "statusCode", 204));
    Map<String, Object> resource =
        Map.of(
            "id", "widgets",
            "name", Map.of("tokens", List.of("widgets")),
            "docs", Map.of(),
            "subresources", List.of(),
            "methods", List.of(method));
    String source =
        emit(ir(Map.of("resources", List.of(resource))), Map.of())
            .get("src/main/java/com/acme/sdk/Widgets.java");
    assertTrue(source.contains("String id"), source);
    assertTrue(source.contains("String expand"), source);
    // Percent-encoded, so an id containing a slash cannot escape its segment.
    assertTrue(source.contains("Query.path(\"/widgets/{id}\""), source);
  }

  @Test
  void aStreamingMethodIsSkippedWithAWarning() {
    // Skipping is honest: a method that JSON-decoded an SSE stream cannot work and looks like it
    // should.
    Map<String, Object> method =
        Map.of(
            "name", Map.of("tokens", List.of("stream")),
            "operationId", "streamEvents",
            "docs", Map.of(),
            "deprecated", Boolean.FALSE,
            "http", Map.of("verb", "get", "path", "/events/stream", "params", List.of()),
            "response",
                Map.of(
                    "kind",
                    "stream",
                    "statusCode",
                    200,
                    "encoding",
                    "sse",
                    "event",
                    Map.of("kind", "unknown")));
    Map<String, Object> resource =
        Map.of(
            "id", "events",
            "name", Map.of("tokens", List.of("events")),
            "docs", Map.of(),
            "subresources", List.of(),
            "methods", List.of(method));
    Emitter emitter =
        new Emitter(
            ir(Map.of("resources", List.of(resource))),
            Map.of("packageName", "com.acme:sdk"),
            BRAND);
    List<Emitter.File> files = emitter.emit(Map.of());
    String source = "";
    for (Emitter.File file : files) {
      if (file.path().endsWith("Events.java")) {
        source = file.contents();
      }
    }
    // The class declaration itself is `public final class Events`, so the assertion is about the
    // *method*.
    assertFalse(source.contains("stream("), "expected no stream method, got:\n" + source);
    assertEquals(1, emitter.warnings().size());
    assertTrue(String.valueOf(emitter.warnings().get(0).get("message")).contains("streaming"));
  }

  @Test
  void noSchemasFileWhenThereIsNothingToValidate() {
    assertNull(emit(ir(Map.of()), Map.of()).get("src/main/java/com/acme/sdk/Schemas.java"));
  }

  @Test
  void thePomUsesTheConfiguredCoordinatesAndDeclaresNoCompileDependencies() {
    String pom = emit(ir(Map.of()), Map.of("packageName", "com.widgetco:sdk")).get("pom.xml");
    assertTrue(pom.contains("<groupId>com.widgetco</groupId>"), pom);
    assertTrue(pom.contains("<artifactId>sdk</artifactId>"), pom);
    // The whole point of the hand-written JSON layer: a library that pins Jackson creates version
    // skew with whatever the consuming application already has.
    //
    // Asserted as "nothing a consumer receives" rather than "no `<dependencies>` block at all",
    // because
    // the generated per-operation tests need JUnit (SPEC.md §3.11). Maven's `test` scope is neither
    // published in the artifact's metadata nor resolved transitively, so the property that matters
    // is
    // unchanged — but the *shape* of the assertion had to change to say what the property is rather
    // than
    // what the file looks like.
    for (String line : pom.split("\n")) {
      if (line.contains("<artifactId>") && line.contains("junit")) {
        continue;
      }
      assertFalse(line.contains("<dependency>") && !pom.contains("<scope>test</scope>"), pom);
    }
    assertTrue(pom.contains("<scope>test</scope>"), pom);
    // Exactly one dependency, and it is the test runner.
    assertEquals(1, pom.split("<dependency>", -1).length - 1, pom);
    assertEquals(1, pom.split("<scope>test</scope>", -1).length - 1, pom);
  }

  @Test
  void noFileNamesTheGeneratorOutsideTheSuppliedBrand() {
    // The brand is carried over the protocol precisely so a target cannot hardcode it. Generated
    // files are
    // files consumers commit, so a rename must not break them.
    Map<String, Object> brand = new LinkedHashMap<>(BRAND);
    brand.put("generatedNotice", "MADE BY XX. DO NOT EDIT.");
    brand.put("name", "xx");
    brand.put("attribution", "_By xx._");
    Emitter emitter =
        new Emitter(
            ir(Map.of("types", List.of(widgetType(Map.of())))),
            Map.of("packageName", "com.acme:sdk"),
            brand);
    List<String> offenders = new ArrayList<>();
    for (Emitter.File file : emitter.emit(Map.of())) {
      if (file.contents().toLowerCase(java.util.Locale.ROOT).contains("besdk")) {
        offenders.add(file.path());
      }
    }
    assertEquals(List.of(), offenders);
  }
}
